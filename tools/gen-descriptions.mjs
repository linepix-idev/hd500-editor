// Keep the offline UI data in sync with the editable description catalog.
import { readFileSync, writeFileSync } from 'node:fs';
const data = JSON.parse(readFileSync(new URL('../catalog/descriptions.json', import.meta.url)));
writeFileSync(new URL('../app/public/js/descriptions-data.js', import.meta.url),
  `// Generated by tools/gen-descriptions.mjs; edit catalog/descriptions.json.\nexport const DESCRIPTIONS = ${JSON.stringify(data, null, 2)};\n`);
